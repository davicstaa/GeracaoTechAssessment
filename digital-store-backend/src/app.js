require('dotenv').config();
const express = require('express');
const path = require('path');
const cors = require('cors');
const swaggerUi = require('swagger-ui-express');
const { handleErrors } = require('./lib/errors');
const app = express();
const allowed = (process.env.CORS_ORIGIN || 'http://localhost:5173').split(',').map(s => s.trim());
app.use(cors({ origin: allowed }));
app.use(express.json({ limit: '8mb' }));
app.use('/uploads', express.static(path.resolve(__dirname, '../uploads')));
app.get('/health', (req, res) => res.json({ status: 'ok', project: 'digital-store-backend' }));
app.use('/docs', swaggerUi.serve, swaggerUi.setup(require('./swagger')));
app.use('/v1/user', require('./routes/userRoutes'));
app.use('/v1/category', require('./routes/categoryRoutes'));
app.use('/v1/product', require('./routes/productRoutes'));
app.use((req, res) => res.status(404).json({ message: 'Rota não encontrada.' }));
app.use(handleErrors);
module.exports = app;
